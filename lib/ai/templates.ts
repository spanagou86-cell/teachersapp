const bankFor = (id: SubjectId): Bank => BANK[id] ?? GENERIC;

export function bankTopic(subjectId: SubjectId): string {
  return bankFor(subjectId).topic;
}

export interface BuildInput {
  subjectId: SubjectId;
  kind: MaterialKind;
  level: Level;
  grade: string;
  /** Used to pick a template (e.g. a graph worksheet) and to prefix block ids. */
  hint: string;
  prefix: string;
}

export function buildBlocks({ subjectId, kind, level, grade, hint, prefix: p }: BuildInput): Block[] {
  const bank = bankFor(subjectId);
  const isGraph = subjectId === "math" && /γραφ|graph|chart|ραβδ/i.test(hint);
  const topic = isGraph ? "Διαβάζω μια γραφική παράσταση" : bank.topic;
  const exercises = (isGraph ? GRAPH_EXERCISES(p) : bank.exercises(p)).map((b) => withLevel(b, level));
  const head: Block = { id: `${p}-h`, type: "heading", text: topic };

  if (kind === "plan") {
    const depth = level === "basic" ? "με εποπτικό υλικό και καθοδήγηση" : level === "advanced" ? "με ανοιχτές ερωτήσεις και ομαδική διερεύνηση" : "με σύντομη εξήγηση και ατομική εξάσκηση";
    return [
      { ...head, text: `Σχέδιο μαθήματος: ${topic}` },
      { id: `${p}-t1`, type: "text", text: `Τάξη: ${grade} · Διάρκεια: 40′` },
      { id: `${p}-t2`, type: "text", text: `Στόχοι: Οι μαθητές να μπορούν να εφαρμόζουν όσα έμαθαν στο «${topic}» ${depth}.` },
      { id: `${p}-t3`, type: "text", text: "Αφόρμηση (5′): Μια ερώτηση από την καθημερινότητα των παιδιών ανοίγει τη συζήτηση." },
      { id: `${p}-t4`, type: "text", text: `Κύρια δραστηριότητα (25′): ${exercises.map((e, i) => `${i + 1}) ${e.text}`).join(" ")}` },
      { id: `${p}-t5`, type: "text", text: "Ανακεφαλαίωση (5′): Δύο μαθητές εξηγούν στην τάξη πώς σκέφτηκαν." },
      { id: `${p}-t6`, type: "text", text: "Αξιολόγηση (5′): Σύντομη ερώτηση εξόδου στο τετράδιο." },
    ];
  }
  if (kind === "summary") {
    return [{ ...head, text: `Περίληψη: ${topic}` }, ...bank.summary.map((text, i) => ({ id: `${p}-s${i}`, type: "text" as const, text }))];
  }
  const intro: Block[] = isGraph
    ? [
        { id: `${p}-i`, type: "text", text: `Η πιο κάτω γραφική παράσταση δείχνει πόσα φρούτα έφεραν οι μαθητές της ${grade} για το κολατσιό τους, σε μια εβδομάδα.` },
        { id: `${p}-c`, type: "chart", text: "", chart: { title: "Φρούτα για κολατσιό", yLabel: "Αριθμός μαθητών", bars: [{ label: "Μήλο", value: 8 }, { label: "Μπανάνα", value: 6 }, { label: "Πορτοκάλι", value: 4 }] } },
      ]
    : [{ id: `${p}-i`, type: "text", text: bank.intro }];
  if (kind === "quiz") {
    return [{ ...head, text: `Μικρό τεστ: ${topic}` }, { id: `${p}-i`, type: "text", text: "Χρόνος: 10 λεπτά · Απάντησε σε όλες τις ερωτήσεις." }, ...intro.filter((b) => b.type === "chart"), ...exercises];
  }
  return [head, ...intro, ...exercises];
}
