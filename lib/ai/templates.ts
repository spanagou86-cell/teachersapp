import type { Block, Level, MaterialKind, SubjectId, Variant } from "../types";

/**
 * Content bank used by the demo AI. In production this is replaced by a model call
 * that reads the uploaded file; the shape of the output (blocks with level variants)
 * stays the same so the editor and history don't change.
 */

type V = [text: string, answer?: string];

function v([text, answer]: V): Variant {
  return answer === undefined ? { text } : { text, answer };
}

function ex(id: string, variants: { basic: V; standard: V; advanced: V; b: V }, lines = 2): Block {
  return {
    id,
    type: "exercise",
    text: variants.standard[0],
    answer: variants.standard[1],
    lines,
    level: "standard",
    variants: { basic: v(variants.basic), standard: v(variants.standard), advanced: v(variants.advanced) },
    variantB: v(variants.b),
  };
}

export function withLevel(block: Block, level: Level): Block {
  const variant = block.variants?.[level];
  if (block.type !== "exercise" || !variant) return block;
  return { ...block, level, text: variant.text, answer: variant.answer };
}

